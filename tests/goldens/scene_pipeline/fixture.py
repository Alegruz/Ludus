"""Deterministic synthetic source for the pbrt-reference-v1 (staircase2) profile.

The fixture exercises every accepted branch of scripts/python/ludus_tools/scene_cook.py:
wallpaper atlas clipping, wood/tile coated diffuse groups, a conductor, solid diffuse
colors, a degenerate triangle, quad PLY faces, `s t` UV names, and the three emitter
forms (axis-aligned PLY rectangle, transformed trianglemesh quad, transformed disk).
It contains no third-party content. The generated tree is committed under `source/`
so a non-Python port can consume it without running this script.
"""
from pathlib import Path
