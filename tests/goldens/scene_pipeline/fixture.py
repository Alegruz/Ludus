def tga(width, height, pixel, alpha=False, top_left=False):
    bits = 32 if alpha else 24
    header = struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, width, height, bits,
                         (0x20 if top_left else 0) | (8 if alpha else 0))
    body = bytearray()
    for y in range(height):
        for x in range(width):
            r, g, b = pixel(x, y)
            body += bytes((b, g, r, 255) if alpha else (b, g, r))
    return header + bytes(body)


def ply(vertices, faces, props=("x", "y", "z", "nx", "ny", "nz", "u", "v"), index="int", count="uint8"):
    lines = ["ply", "format binary_little_endian 1.0", "comment Ludus golden fixture",
             f"element vertex {len(vertices)}"]
    lines += [f"property float {p}" for p in props]
    lines += [f"element face {len(faces)}", f"property list {count} {index} vertex_indices", "end_header"]
    data = bytearray(("\n".join(lines) + "\n").encode("ascii"))
    for v in vertices:
        data += struct.pack("<" + "f" * len(props), *v)
    for f in faces:
        data += struct.pack("<B" + ("i" if index == "int" else "I") * len(f), len(f), *f)
    return bytes(data)


